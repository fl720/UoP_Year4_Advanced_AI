function y = shekel_func(x)
    A = [4.0, 4.0, 4.0, 4.0;
         1.0, 1.0, 1.0, 1.0;
         8.0, 8.0, 8.0, 8.0;
         6.0, 6.0, 6.0, 6.0;
         3.0, 7.0, 3.0, 7.0;
         2.0, 9.0, 2.0, 9.0;
         5.0, 5.0, 3.0, 3.0;
         8.0, 1.0, 8.0, 1.0;
         6.0, 2.0, 6.0, 2.0;
         7.0, 3.6, 7.0, 3.6];

    C = [0.1; 0.2; 0.2; 0.4; 0.4; 0.6; 0.3; 0.7; 0.5; 0.5];

    m = 5; 
    
    y = 0;
    for i = 1:m
        inner_sum = sum((x - A(i, :)).^2);
        y = y - (inner_sum + C(i))^(-1); 
    end
end